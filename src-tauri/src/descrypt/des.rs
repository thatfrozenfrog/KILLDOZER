fn permute(value: u64, table: &[usize]) -> u64 {
    table
        .iter()
        .fold(0, |out, &src| (out << 1) | ((value >> (64 - src)) & 1))
}
fn key_bits(key: [u8; 8]) -> [u8; 64] {
    let mut out = [0; 64];
    for i in 0..64 {
        out[i] = (key[i / 8] >> (7 - i % 8)) & 1;
    }
    out
}
pub fn round_keys(key: [u8; 8]) -> [[u8; 48]; 16] {
    let raw = key_bits(key);
    let mut cd = [0; 56];
    for i in 0..56 {
        cd[i] = raw[PC1[i] - 1];
    }
    let mut out = [[0; 48]; 16];
    for round in 0..16 {
        cd[..28].rotate_left(SHIFTS[round]);
        cd[28..].rotate_left(SHIFTS[round]);
        for i in 0..48 {
            out[round][i] = cd[PC2[i] - 1];
        }
    }
    out
}
fn f(right: u32, key: &[u8; 48], e: &[usize; 48]) -> u32 {
    let mut s = 0u32;
    for box_no in 0..8 {
        let mut v = 0u8;
        for j in 0..6 {
            let bit = ((right >> (31 - e[box_no * 6 + j])) & 1) as u8 ^ key[box_no * 6 + j];
            v = (v << 1) | bit;
        }
        let row = ((v & 0x20) >> 4) | (v & 1);
        let col = (v >> 1) & 15;
        s = (s << 4) | S[box_no][row as usize][col as usize] as u32;
    }
    P.iter()
        .fold(0, |out, &src| (out << 1) | ((s >> (32 - src)) & 1))
}
pub fn encrypt(block: u64, keys: &[[u8; 48]; 16], salt: &SaltMap) -> u64 {
    let ip = permute(block, &IP);
    let (mut l, mut r) = ((ip >> 32) as u32, ip as u32);
    for key in keys {
        let next = l ^ f(r, key, &salt.expansion);
        l = r;
        r = next;
    }
    permute((r as u64) << 32 | l as u64, &FP)
}

fn sbox(index: usize, input: [BsWord; 6]) -> [BsWord; 4] {
    let mut out = [0; 4];
    for lane_value in 0..64 {
        let row = ((lane_value & 32) >> 4) | (lane_value & 1);
        let col = (lane_value >> 1) & 15;
        let value = S[index][row][col];
        let mut term = !0u64;
        for (bit, input_bit) in input.iter().enumerate() {
            term &= if lane_value & (1 << (5 - bit)) != 0 {
                *input_bit
            } else {
                !*input_bit
            };
        }
        for (bit, output_bit) in out.iter_mut().enumerate() {
            if value & (1 << (3 - bit)) != 0 {
                *output_bit |= term;
            }
        }
    }
    out
}
pub fn encrypt_bitsliced(state: &mut BitsliceState, key: &[BsWord; 56], salt: &SaltMap) {
    let mut ip = [0; 64];
    for i in 0..64 {
        ip[i] = state[IP[i] - 1];
    }
    let (mut l, mut r) = ([0; 32], [0; 32]);
    l.copy_from_slice(&ip[..32]);
    r.copy_from_slice(&ip[32..]);
    let mut raw_key = [0; 64];
    for byte in 0..8 {
        for bit in 0..7 {
            raw_key[byte * 8 + bit] = key[byte * 7 + bit];
        }
    }
    let mut cd = [0; 56];
    for i in 0..56 {
        cd[i] = raw_key[PC1[i] - 1];
    }
    for shift in SHIFTS {
        cd[..28].rotate_left(shift);
        cd[28..].rotate_left(shift);
        let mut raw = [0; 32];
        for b in 0..8 {
            let mut input = [0; 6];
            for j in 0..6 {
                input[j] = r[salt.expansion[b * 6 + j]] ^ cd[PC2[b * 6 + j] - 1];
            }
            raw[b * 4..b * 4 + 4].copy_from_slice(&sbox(b, input));
        }
        let mut next = [0; 32];
        for i in 0..32 {
            next[i] = l[i] ^ raw[P[i] - 1];
        }
        l = r;
        r = next;
    }
    let mut pre = [0; 64];
    pre[..32].copy_from_slice(&r);
    pre[32..].copy_from_slice(&l);
    for i in 0..64 {
        state[i] = pre[FP[i] - 1];
    }
}
